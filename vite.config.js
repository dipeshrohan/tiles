import { defineConfig } from 'vite';
import { helpPlugin } from './scripts/help.js';
import { messagesPlugin } from './scripts/messages.js';

const outDir = process.env.TILES_OUT_DIR ?? 'js';

// Builds the app into one classic (non-module) script, js/tiles.bundle.js.
// index.html loads it with a plain <script>, so the app also works when the
// file is opened straight from disk (file://), where browsers block module
// scripts.
export default defineConfig({
  // The user guide, as each page's help (U4.04): js/help-data.js, beside the bundle; and the message
  // catalogues (U6.01): js/messages-<code>.js.
  plugins: [helpPlugin(outDir), messagesPlugin(outDir)],
  build: {
    outDir,
    emptyOutDir: false,
    // Minified (U5.01): the bundle is generated, read from js/; its gzipped size is budgeted (test:perf).
    minify: true,
    sourcemap: false,
    target: 'es2022',
    lib: {
      entry: 'js/app.ts',
      formats: ['iife'],
      name: 'Tiles',
      fileName: () => 'tiles.bundle.js',
    },
    rollupOptions: { output: { banner: '// Generated by Vite from js/**/*. Do not edit; run `npm run build`.' } },
  },
  test: {
    include: ['test/**/*.test.{js,ts}'],
    // The English catalogue, as index.html's js/messages-en.js gives it to the page.
    setupFiles: ['test/setup.js'],
  },
});
