// Writes js/lib/glossary-data.ts: the terms of docs/ui/glossary.md (U4.05), for the term tooltips on
// pages (term() in js/lib/ui.ts) and the Glossary page. Run `npm run glossary` after changing the
// glossary; test/glossary.test.js fails when the file is stale. Each `##` is a group, each `###` a
// term with one paragraph of plain words.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { slugger } from './help.js';

const ROOT = resolve(fileURLToPath(import.meta.url), '../..');
const SOURCE = 'docs/ui/glossary.md';

// The terms, in the glossary's order: key (the heading's anchor), term, group and definition.
export function parse(markdown) {
  const slug = slugger();
  const terms = [];
  let group = null;
  let current = null;
  const close = () => {
    if (!current) return;
    const text = current.lines.join(' ').replace(/\s+/g, ' ').trim();
    if (!text) throw new Error(`${SOURCE}: "${current.term}" has no definition`);
    if (/[`*<>#|]|\]\(/.test(text)) throw new Error(`${SOURCE}: "${current.term}" has formatting; write plain words`);
    if (current.paragraphs > 1) throw new Error(`${SOURCE}: "${current.term}" has more than one paragraph`);
    terms.push({ key: current.key, term: current.term, group: current.group, text });
    current = null;
  };
  for (const line of markdown.split('\n')) {
    const h = /^(#{1,3})\s+(.*?)\s*$/.exec(line);
    if (h) {
      close();
      const key = slug(h[2]);
      if (h[1] === '##') group = h[2];
      else if (h[1] === '###') {
        if (!group) throw new Error(`${SOURCE}: "${h[2]}" is not in a group`);
        current = { key, term: h[2], group, lines: [], paragraphs: 0, blank: true };
      }
      continue;
    }
    if (!current) continue;
    if (!line.trim()) {
      current.blank = true;
      continue;
    }
    if (current.blank) current.paragraphs++;
    current.blank = false;
    current.lines.push(line.trim());
  }
  close();
  const seen = new Set();
  for (const t of terms) {
    if (seen.has(t.term.toLowerCase())) throw new Error(`${SOURCE}: "${t.term}" is there twice`);
    seen.add(t.term.toLowerCase());
  }
  return terms;
}

export function generate() {
  const terms = parse(readFileSync(join(ROOT, SOURCE), 'utf8'));
  const entries = terms
    .map(
      (t) =>
        `  ${JSON.stringify(t.key)}: { term: ${JSON.stringify(t.term)}, group: ${JSON.stringify(t.group)}, text: ${JSON.stringify(t.text)} },`,
    )
    .join('\n');
  return `// Generated by scripts/glossary.js from ${SOURCE}: don't edit, change the glossary and run \`npm run glossary\`.

export const GLOSSARY = {
${entries}
} as const;

export type GlossaryKey = keyof typeof GLOSSARY;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(ROOT, 'js/lib/glossary-data.ts'), generate());
  console.log('js/lib/glossary-data.ts: written');
}
